class Wire(Flowable):
    """极简界面示意图（矢量线框），黑白友好，不依赖外部图片。"""
    def __init__(self, title, blocks, width=165*mm, row_h=6.6*mm):
        Flowable.__init__(self)
        self.title = title
        self.blocks = blocks
        self.width = width
        self.row_h = row_h
        self.height = 7*mm + row_h*len(blocks) + 2*mm

    def draw(self):
        c = self.canv
        w, h = self.width, self.height
        # 外框
        c.setLineWidth(1.0)
        c.setStrokeColor(colors.HexColor("#333333"))
        c.rect(0, 0, w, h)
        # 标题栏
        c.setFillColor(colors.HexColor("#efefef"))
        c.rect(0, h-7*mm, w, 7*mm, stroke=1, fill=1)
        c.setFillColor(colors.black)
        c.setFont("STSong-Light", 9)
        c.drawString(3*mm, h-4.9*mm, self.title)
        # 内容块
        y = h - 7*mm
        c.setFont("STSong-Light", 8.5)
        for b in self.blocks:
            y -= self.row_h
            c.setStrokeColor(colors.HexColor("#888888"))
            c.setLineWidth(0.5)
            c.rect(3*mm, y+0.9*mm, w-6*mm, self.row_h-1.8*mm)
            c.setFillColor(colors.HexColor("#333333"))
            c.drawString(5*mm, y+self.row_h/2-1.2*mm, b)


