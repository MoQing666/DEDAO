def prepare_thumbs():
    """按目标高度等比缩放截图，避免 Word 中图片超出版心。"""
    os.makedirs(THUMB, exist_ok=True)
    meta = {}
    for name, h_cm in SHOT_H.items():
        src = os.path.join(SHOT, name + ".png")
        im = Image.open(src).convert("RGB")
        iw, ih = im.size
        th = px(h_cm)
        tw = max(1, int(round(th * iw / ih)))
        im = im.resize((tw, th), Image.LANCZOS)
        dst = os.path.join(THUMB, name + ".png")
        im.save(dst, "PNG", optimize=True)
        meta[name] = (tw, th)
    return meta


META = prepare_thumbs()


def img_tag(name):
    w, h = META[name]
    path = os.path.join(THUMB, name + ".png").replace("\\", "/")
    return f'<img src="{path}" width="{w}" height="{h}"/>'


