def tbl(rows, head=True):
    out = ['<table class="grid">']
    for i, r in enumerate(rows):
        tag = "th" if (head and i == 0) else "td"
        out.append("<tr>" + "".join(f"<{tag}>{c}</{tag}>" for c in r) + "</tr>")
    out.append("</table>")
    H.append("".join(out))


def wire(title, blocks):
    """矢量示意图：以单列表格模拟线框块。"""
    rows = [[b] for b in blocks]
    out = [f'<p class="figtitle">{title}</p>', '<table class="wire">']
    for r in rows:
        out.append(f'<tr><td>{r[0]}</td></tr>')
    out.append("</table>")
    H.append("".join(out))
    H.append(f'<p class="cap">{title}</p>')


def shots(items):
    """并排截图 + 图注。items: [(文件名, 图注), ...]"""
