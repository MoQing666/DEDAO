def _shot_img(fname, target_h):
    """按原始纵横比缩放截图至目标高度，返回 (Image对象, 宽, 高)。"""
    path = os.path.join(SHOT, fname)
    iw, ih = ImageReader(path).getSize()
    h = target_h
    w = target_h * iw / ih
    img = RLImage(path, width=w, height=h)
    return img, w, h


def shot_row(items, target_h=95*mm):
    """并排插入一组真实界面截图。items: [(文件名, 图注), ...]
    自动按比例排版，超出正文宽度时整体缩小。图注位于各图正下方。"""
    imgs, caps = [], []
    ws, total = [], 0
    for fname, cap_txt in items:
        img, w, h = _shot_img(fname, target_h)
        imgs.append(img)
        caps.append(Paragraph(cap_txt, cap))
        ws.append(w + 4*mm)
        total += w + 4*mm
    max_total = 174*mm
    if total > max_total:
        k = max_total / total
        imgs = [RLImage(os.path.join(SHOT, f),
                        width=(w-4*mm)*k, height=(target_h)*k)
                for (f, _), w in zip(items, ws)]
        caps = [Paragraph(c, cap) for _, c in items]
        ws = [w*k for w in ws]
    t = Table([imgs, caps], colWidths=ws)
    t.setStyle(TableStyle([
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, 0), "MIDDLE"),
        ("BOX", (0, 0), (-1, 0), 0.6, colors.HexColor("#888888")),
        ("VALIGN", (0, 1), (-1, 1), "TOP"),
        ("TOPPADDING", (0, 1), (-1, 1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 1),
        ("RIGHTPADDING", (0, 0), (-1, -1), 1),
    ]))
    S.append(KeepTogether([Spacer(1, 4), t, Spacer(1, 3)]))


